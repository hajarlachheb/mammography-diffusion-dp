"""LaTeX publication tables from the aggregate CSVs in results/verified_summary/.

Ported from the project scripts that produced the manuscript tables (S3_combine_eps_results_and_figures.py,
M1_02_comparison_figure_and_table.py, S6_verify_quality_metrics_table.py, P4_publication_tables.py), including
the final caption sentences. Only the input locations changed. tests/test_reproduce_outputs.py checks that the
regenerated table bodies equal results/publication_tables/.
"""
import csv
from pathlib import Path

EPS = (1, 6, 60)
DSS = ("cbis", "bcdr")
M = ("auroc", "auprc_malignant", "auprc_benign")
DS_NAME = {"cbis": "CBIS-DDSM test", "bcdr": "BCDR test"}


def _rd(p):
    return list(csv.DictReader(open(p)))


def _pm(r, m):
    return f"{float(r[m + '_mean']):.3f}$\\pm${float(r[m + '_sd_ddof1']):.3f}"


def table1_main(summary_csv, paired_csv):
    S = {(int(r["epsilon_target"]), r["arm"], r["dataset"]): r for r in _rd(summary_csv)}
    P = {(int(r["epsilon_target"]), r["dataset"], r["metric"]): r for r in _rd(paired_csv) if r["level"].startswith("mean of")}
    L = [r"% Generated by scripts/reproduce_tables.py from results/verified_summary/main_{summary,paired_differences}.csv",
         r"% Requires \usepackage{booktabs}",
         r"\begin{table}[t]\centering\scriptsize\setlength{\tabcolsep}{2.2pt}",
         r"\caption{Head-only DP-SGD on a frozen ImageNet Swin-T with the reference two-layer head (296{,}066 trainable parameters), "
         r"trained on 1{,}104 real CBIS-DDSM patches (Real) or the same patches plus 3{,}000 CC-NET patches in one DP-SGD mechanism "
         r"(Real+CC-NET). Mean$\pm$sample SD (ddof$=$1) over $n=3$ independently trained seeds (42/43/44). $\Delta$: mean of the three "
         r"seed-paired differences in AUROC, with the 95\% patient-cluster bootstrap CI of the test set in brackets (test-sampling "
         r"uncertainty only; between-seed variability is the SD) and $k/3$ seeds with $\Delta>0$. AUPRC$_\mathrm{mal}$ / "
         r"AUPRC$_\mathrm{ben}$ take malignant / benign as the positive class. $\varepsilon$ ($\delta=10^{-4}$, RDP) is the full-run, "
         r"image-level budget of the classifier only; the generator is not private. SDs printed as 0.000 are $<0.0005$; the three seeds are distinct models with different per-image predictions.}",
         r"\label{tab:main_results}", r"\begin{tabular}{llcccccc}", r"\toprule",
         r" & & \multicolumn{3}{c}{CBIS-DDSM test (402 img / 212 pat.)} & \multicolumn{3}{c}{BCDR test (1{,}106 img)} \\",
         r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
         r"$\varepsilon$ & Training data & AUROC & AUPRC$_\mathrm{mal}$ & AUPRC$_\mathrm{ben}$ & AUROC & AUPRC$_\mathrm{mal}$ & AUPRC$_\mathrm{ben}$ \\",
         r"\midrule"]
    for e in EPS:
        for i, arm in enumerate(("real", "realsyn")):
            L.append(f"{e if i == 0 else ''} & {'Real' if arm == 'real' else 'Real+CC-NET'} & "
                     + " & ".join(_pm(S[(e, arm, ds)], m) for ds in DSS for m in M) + r" \\")
        cells = []
        for ds in DSS:
            p = P[(e, ds, "auroc")]
            cells.append(rf"\multicolumn{{3}}{{c}}{{$\Delta$AUROC {float(p['difference']):+.3f} "
                         rf"[{float(p['test_sampling_ci95_lo']):+.3f}, {float(p['test_sampling_ci95_hi']):+.3f}], {p['n_seeds_positive']}/3}}")
        L.append(r" & \textit{paired} & " + " & ".join(cells) + r" \\")
        if e != EPS[-1]:
            L.append(r"\addlinespace")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(L) + "\n"


def table2_m1(summary_csv, paired_csv):
    S = {(r["condition"], r["dataset"]): r for r in _rd(summary_csv)}
    P = {(r["comparison"][:6].strip(), r["dataset"], r["metric"]): r for r in _rd(paired_csv) if r["level"].startswith("mean")}
    L = [r"% Generated by scripts/reproduce_tables.py from results/verified_summary/m1_{summary,paired_differences}.csv",
         r"% Requires \usepackage{booktabs}",
         r"\begin{table}[t]\centering\scriptsize\setlength{\tabcolsep}{2.2pt}",
         r"\caption{Optimisation control at $\varepsilon=6$ ($\delta=10^{-4}$). A: Real-only DP (batch 128, $q=1/9$, $\sigma=4.34$, "
         r"2{,}700 steps). M1: Real-only DP with Real+CC-NET's sampling rate, noise multiplier and step count (batch 34, $q=1/33$, "
         r"$\sigma=2.34$, 9{,}900 steps). C: Real+CC-NET DP (1{,}104 real + 3{,}000 CC-NET, $q=1/33$, $\sigma=2.34$, 9{,}900 steps). "
         r"Mean$\pm$sample SD over $n=3$ independently trained seeds. Contrasts: mean of three seed-paired differences in AUROC, "
         r"95\% patient-cluster bootstrap CI of the test set (test-sampling uncertainty only) and $k/3$ seeds with $\Delta>0$; between-seed variability is the SD. A follows the reference protocol of Osuala et al.; M1 is an optimisation control with a non-reference batch size, not a replacement for A.}",
         r"\label{tab:m1}", r"\begin{tabular}{lcccccc}", r"\toprule",
         r" & \multicolumn{3}{c}{CBIS-DDSM test} & \multicolumn{3}{c}{BCDR test} \\", r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
         r"Condition & AUROC & AUPRC$_\mathrm{mal}$ & AUPRC$_\mathrm{ben}$ & AUROC & AUPRC$_\mathrm{mal}$ & AUPRC$_\mathrm{ben}$ \\", r"\midrule"]
    for a, nm in (("A", "A: Real-only"), ("M1", "M1: Real-only, matched $q$/$\\sigma$/steps"), ("C", "C: Real+CC-NET")):
        L.append(nm + " & " + " & ".join(_pm(S[(a, ds)], m) for ds in DSS for m in M) + r" \\")
    L.append(r"\midrule")
    for key, nm in (("C - M1", "C $-$ M1"), ("M1 - A", "M1 $-$ A"), ("C - A", "C $-$ A")):
        cells = []
        for ds in DSS:
            p = P[(key, ds, "auroc")]
            cells.append(rf"\multicolumn{{3}}{{c}}{{$\Delta$AUROC {float(p['difference']):+.3f} "
                         rf"[{float(p['test_sampling_ci95_lo']):+.3f}, {float(p['test_sampling_ci95_hi']):+.3f}], {p['n_seeds_positive']}/3}}")
        L.append(nm + " & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(L) + "\n"


def table3_quality(quality_csv):
    rows = {r["comparison"]: r for r in _rd(quality_csv)}
    order = [("Real vs real (reference)", "CBIS train A vs B (patient-disjoint)"), ("", "CBIS train vs CBIS test"),
             ("Real vs real (cross-site)", "CBIS train vs BCDR test"),
             ("Synthetic vs real", "CC-NET vs CBIS train"), ("", "MCGAN vs CBIS train")]
    L = [r"% Generated by scripts/reproduce_tables.py from results/verified_summary/image_quality_fid_frd.csv",
         r"\begin{table}[t]\centering\scriptsize\setlength{\tabcolsep}{4pt}",
         r"\caption{Synthesis fidelity at $128\times128$. Fr\'echet distances between equal-size subsamples ($n=400$ per side); "
         r"mean$\pm$SD over 20 seeded subsample draws from one fixed image pool per source. The SD reflects subsampling only, "
         r"not variation across independently trained generators (one generator per method). FID uses ImageNet Inception-v3 "
         r"features; FRD$_\mathrm{v1}$ uses PyRadiomics features ($\log d_F^2$). Real-vs-real rows give the reference scale. "
         r"CC-NET images ($256\times256$) were resized to 128. FID depends on $n$ and on a natural-image feature space, so values "
         r"are comparable only within this table. The FRD$_\mathrm{v1}$ subsample intervals of the two generators overlap, so the "
         r"FRD difference is not conclusive. MCGAN: the published 3{,}000 images, attributed by GAN inversion to the checkpoint "
         r"that medigan documents as trained on CBIS-DDSM test; they are compared with CBIS train only.}",
         r"\label{tab:quality}", r"\begin{tabular}{llcc}", r"\toprule",
         r" & Comparison & FID$_\mathrm{ImageNet}$ $\downarrow$ & FRD$_\mathrm{v1}$ $\downarrow$ \\", r"\midrule"]
    for i, (g, k) in enumerate(order):
        r = rows[k]
        if g and i:
            L.append(r"\addlinespace")
        L.append(f"{g} & {k} & {float(r['fid_imagenet_mean']):.1f}$\\pm${float(r['fid_imagenet_sd']):.1f} & "
                 f"{float(r['frd_v1_mean']):.2f}$\\pm${float(r['frd_v1_sd']):.2f} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(L) + "\n"


def tableS1_osuala(summary_csv, osuala_csv):
    S = {(int(r["epsilon_target"]), r["arm"], r["dataset"]): r for r in _rd(summary_csv)}
    O = {(int(r["epsilon"]), r["arm"], r["dataset"]): r for r in _rd(osuala_csv)}
    T = [r"% Generated by scripts/reproduce_tables.py from results/verified_summary/{main_summary,osuala2024_reported_table1}.csv",
         r"\begin{table}[t]\centering\scriptsize\setlength{\tabcolsep}{3pt}",
         r"\caption{AUROC of the clean reproduction versus the values reported by Osuala et al.\ (Table~1; mean$\pm$SD over 3 seeds). "
         r"Real-only rows use the same data and recipe in both. The Real+Syn rows differ in the generator: MCGAN in the original "
         r"study and CC-NET here, so those differences are not a reproduction test. Values are not pooled across studies.}",
         r"\label{tab:osuala_comparison}", r"\begin{tabular}{lllccc}", r"\toprule",
         r"$\varepsilon$ & Test set & Arm & Osuala et al. & This work & Difference \\", r"\midrule"]
    for e in EPS:
        for ds in DSS:
            for arm in ("real", "realsyn"):
                o, r = O[(e, arm, ds)], S[(e, arm, ds)]
                pm, psd = float(o["auroc_mean"]), float(o["auroc_std"])
                cm, csd = round(float(r["auroc_mean"]), 4), round(float(r["auroc_sd_ddof1"]), 4)
                T.append(f"{e} & {DS_NAME[ds]} & {'Real' if arm == 'real' else 'Real+Syn'} & "
                         f"{pm:.3f}$\\pm${psd:.3f} & {cm:.3f}$\\pm${csd:.3f} & {round(float(r['auroc_mean']) - pm, 4):+.3f} \\\\")
    T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(T) + "\n"
